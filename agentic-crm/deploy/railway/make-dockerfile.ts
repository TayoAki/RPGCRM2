#!/usr/bin/env bun
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

/*
 * Railway builds from one context with no named build contexts, so the CRM and the tenant package
 * can't be passed the way compose.yml passes them. This rewrites OpenDuet's Dockerfile for a build
 * from agentic-crm/: its own files are prefixed with openduet/openbot/, and `atomic-crm` and
 * `tenant` become stages. Run it after a vendor sync; --check fails when the output is stale.
 *
 *   bun agentic-crm/deploy/railway/make-dockerfile.ts [--check]
 */

const OPENBOT = "openduet/openbot";
const here = import.meta.dir;
const root = resolve(here, "../..");

function prefixSources(line: string): string {
  const [instruction, ...paths] = line.trim().split(/\s+/);
  const destination = paths.pop();
  return [
    instruction,
    ...paths.map((path) => `${OPENBOT}/${path}`),
    destination,
  ].join(" ");
}

export function railwayDockerfile(upstream: string): string {
  let stage = "";
  const lines = upstream.split("\n").flatMap((line) => {
    const from = line.match(/^FROM\s+\S+\s+AS\s+(\S+)/i);
    if (from) stage = from[1];
    if (!/^COPY\s/.test(line) || line.includes("--from=")) return [line];
    if (stage === "tenant") {
      return [
        "COPY tenant /",
        "",
        "FROM scratch AS atomic-crm",
        "COPY atomic-crm/package.json atomic-crm/package-lock.json atomic-crm/.npmrc /",
        "COPY atomic-crm/src /src",
      ];
    }
    return [prefixSources(line)];
  });
  return [
    "# Generated by deploy/railway/make-dockerfile.ts from openduet/openbot/Dockerfile. Don't edit.",
    ...lines,
    "",
    "COPY deploy/railway/migrate.sh /etc/s6-overlay/scripts/migrate.sh",
    "COPY deploy/railway/first-admin.ts /app/server/scripts/first-admin.ts",
    "",
  ].join("\n");
}

export function railwayDockerignore(upstream: string): string {
  const lines = upstream
    .split("\n")
    .filter((line) => line.trim() && !line.startsWith("#"))
    .map((line) => {
      const negated = line.startsWith("!");
      const pattern = negated ? line.slice(1) : line;
      const prefixed = pattern.startsWith("**/")
        ? pattern
        : `${OPENBOT}/${pattern}`;
      return negated ? `!${prefixed}` : prefixed;
    });
  return [
    "# Generated by deploy/railway/make-dockerfile.ts. Don't edit.",
    "**/node_modules",
    "**/.env",
    ".git",
    "deploy/customers",
    ...lines,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const outputs = [
    {
      path: resolve(here, "Dockerfile"),
      text: railwayDockerfile(
        readFileSync(resolve(root, OPENBOT, "Dockerfile"), "utf8"),
      ),
    },
    {
      path: resolve(root, ".dockerignore"),
      text: railwayDockerignore(
        readFileSync(resolve(root, OPENBOT, ".dockerignore"), "utf8"),
      ),
    },
  ];
  const check = process.argv.includes("--check");
  for (const { path, text } of outputs) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current === text) continue;
    if (check) {
      console.error(`${path} is stale. Run deploy/railway/make-dockerfile.ts.`);
      process.exit(1);
    }
    writeFileSync(path, text);
    console.log(`Wrote ${path}`);
  }
}
